-- ── 1. CLEAN SLATE (DROP EVERYTHING) ────────────────────────────────
-- This removes all existing objects to ensure a perfect 1-to-1 sync with the app logic.
DROP VIEW IF EXISTS public.view_department_analytics;
DROP TABLE IF EXISTS public.announcements;
DROP TABLE IF EXISTS public.daily_logs;
DROP TABLE IF EXISTS public.amal_tasks;
DROP TABLE IF EXISTS public.profiles;
